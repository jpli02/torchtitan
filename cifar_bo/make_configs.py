"""Write the run_experiment.py configs of the CIFAR-10 optimizer comparison of 2026-11-22 (user: "the current cifar result is
not beating gp hedge, try use better gpt model like gpt-6-luna").

Setting = the earlier comparison (configs/cifar10_gp_hedge.yaml, cifar10_gpt_explanation.yaml): ResNet-18, 10 epochs, batch
128, metric validation_accuracy (= test accuracy in objective/cifar.py), 3 SGD knobs (lr, momentum, weight decay), 10
evaluations, explanations on. One config per (arm, first seed), 2 replicates each, so seeds 42-45 run as 2 x 2 in parallel:

  luna6_default  gpt-6-luna with the shipped prompt (optim/chatgpt_prompt.txt)    -> only the model changes
  luna6_budget   gpt-6-luna with cifar_bo/prompts/cifar_budget_blackbox.txt        -> still anonymous x0..x2, no task
                 knowledge; adds the budget (10), an interior opening design, joint modelling and noise awareness
  gp_hedge       skopt GP + gp_hedge, n_initial 10 (= the budget, so its 10 points are skopt's grid design), rerun on the
                 same code and seeds so every arm is matched seed by seed

Trajectories (prompt, response, reasoning per step) go to TRAJ/<arm>/ (memory: always save LLM BO trajectories).

  /home/jli199/boptim-agent/.venv/bin/python cifar_bo/make_configs.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "configs")
TRAJ = "/home/jli199/boptim_scratch/cifar_bo_1122/trajectories"
ARMS = {
    "luna6_default": {"optim": "chatgpt", "model": "gpt-6-luna"},
    "luna6_budget": {"optim": "chatgpt", "model": "gpt-6-luna"},
    # informed: cifar_bo/prompts/cifar_informed.txt names the task and the three knobs (no suggested values), so the model can
    # use its own prior; a different claim from the black-box arms (prior knowledge, not search), reported separately
    "luna6_informed": {"optim": "chatgpt", "model": "gpt-6-luna"},
    # second round (after seeds 42/44): the shipped prompt wasted evaluations 2-3 on the box corners in both luna6_default
    # runs; minfix = shipped prompt + two lines (budget 10, no corners), nothing else changed (prompts/cifar_minfix.txt)
    "luna6_minfix": {"optim": "chatgpt", "model": "gpt-6-luna"},
    # a newer model on the shipped prompt (OpenAI lists gpt-6.2-sol for this key on 2026-11-22)
    "sol62_default": {"optim": "chatgpt", "model": "gpt-6.2-sol"},
    "gp_hedge": {"optim": "gp_hedge", "model": None},
}

os.makedirs(OUT, exist_ok=True)
for arm, a in ARMS.items():
    for seed in (42, 44):
        lines = ["# generated by cifar_bo/make_configs.py", "replicates: 2", "no_explanation: false", ""]
        if a["model"]:
            lines += ["models:", f'  chatgpt: "{a["model"]}"', ""]
        lines += [
            "experiments:",
            f"  - optim: {a['optim']}",
            "    objective:",
            "      type: cifar10",
            "      n_epochs: 10",
            "      train_batch_size: 128",
            "      metrics: validation_accuracy",
            "    batch_size: 1",
            "    max_iter: 10",
            f"    optim_seed: {seed}",
            f"    objective_seed: {seed}",
            f"    trajectory-dir: {TRAJ}/{arm}",
        ]
        p = os.path.join(OUT, f"{arm}_s{seed}.yaml")
        open(p, "w").write("\n".join(lines) + "\n")
        print(p)
